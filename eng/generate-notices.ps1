#!/usr/bin/env pwsh
<#
.SYNOPSIS
  Regenerates THIRD_PARTY_NOTICES.md from the current Cargo dependency graph.
#>
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot

if (-not (Get-Command cargo-about -ErrorAction SilentlyContinue)) {
    Write-Host "Installing cargo-about..."
    cargo install cargo-about --locked --features cli | Out-Null
}

$header = "# Third-Party Notices`n`nGenerated by ``cargo about generate eng/about.hbs -o THIRD_PARTY_NOTICES.md`` (see ``eng/generate-notices.ps1``). Do not edit by hand - regenerate instead.`n`n"

Push-Location $root
try {
    cargo about generate eng/about.hbs -o THIRD_PARTY_NOTICES_BODY.tmp.md
    $body = Get-Content THIRD_PARTY_NOTICES_BODY.tmp.md -Raw
    Set-Content THIRD_PARTY_NOTICES.md ($header + $body)
    Remove-Item THIRD_PARTY_NOTICES_BODY.tmp.md
    Write-Host "Wrote THIRD_PARTY_NOTICES.md" -ForegroundColor Green
}
finally {
    Pop-Location
}
